# ── content: per-entry statistics ───────────────────────────────────────────────────────────────

def test_basic_statistics_and_change_counting():
    raw = make_log({'/Sensor/A': [wave(k) for k in range(N)], '/Cfg/K': [7.0] + [7.0] * (N - 1)})
    ix, st = stats_of(raw)
    a, k = by_name(st)['/Sensor/A'], by_name(st)['/Cfg/K']
    assert a.n_records == N and a.bytes > 0 and not a.constant and a.n_changes > 20
    assert a.num_min == pytest.approx(-3) and a.num_max < 4 and a.num_mean == pytest.approx(sum(wave(i) for i in range(N)) / N)
    assert k.constant and k.distinct == 1 and k.n_changes == 0 and k.num_min == k.num_max == 7.0
    assert st[ix.cycle_entry_id].n_records == N
    assert sum(s.bytes for s in st.values()) == ix.data_bytes                    # the window is the whole log


def test_distinct_count_stops_at_the_cap_and_samples_are_kept():
    raw = make_log({'/X': [float(k) for k in range(300)]})
    _, st = stats_of(raw)
    x = by_name(st)['/X']
    assert x.distinct == content.DISTINCT_CAP and x.distinct_capped and not x.constant
    assert [struct.unpack('<d', s)[0] for s in x.samples] == [0.0, 1.0, 2.0]


def test_hashes_depend_on_values_and_times_separately():
    vals = [wave(k) for k in range(N)]
    raw = make_log({'/A': vals, '/B': vals, '/C': vals, '/D': vals[::-1]}, offsets={'/C': 5_000})
    _, st = stats_of(raw)
    n = by_name(st)
    assert n['/A'].seq_hash == n['/B'].seq_hash == n['/C'].seq_hash != n['/D'].seq_hash
    assert n['/A'].time_hash == n['/B'].time_hash != n['/C'].time_hash


def test_a_window_restricts_everything_to_the_kept_periods():
    # /S is constant for the first 100 cycles, then changes every cycle
    raw = make_log({'/S': [1.0] * 100 + [float(k) for k in range(100)]})
    ix = build_index(raw)
    first, second = TrimPlan([Segment(0.0, 1.9)]), TrimPlan([Segment(2.0, 4.0)])
    r1 = resolve_plan(ix, first).ranges
    r2 = resolve_plan(ix, second).ranges
    s1 = by_name(content.analyze_content(raw, ix.header_end, [(r.lo_us, r.hi_us) for r in r1]))['/S']
    s2 = by_name(content.analyze_content(raw, ix.header_end, [(r.lo_us, r.hi_us) for r in r2]))['/S']
    whole = by_name(content.analyze_content(raw, ix.header_end))['/S']
    assert s1.constant and s1.n_records == 95 and not whole.constant and not s2.constant
    assert s1.n_records + s2.n_records <= whole.n_records
    assert s2.first_ts_us >= r2[0].lo_us


def test_entries_with_no_records_in_the_window_are_still_listed():
    raw = make_log({'/Early': [1.0, 2.0, 3.0] + [None] * (N - 3), '/Always': [wave(k) for k in range(N)]})
    ix = build_index(raw)
    rng = [(r.lo_us, r.hi_us) for r in resolve_plan(ix, TrimPlan([Segment(2.0, 3.0)])).ranges]
    st = by_name(content.analyze_content(raw, ix.header_end, rng))
    assert st['/Early'].n_records == 0 and not st['/Early'].constant and st['/Always'].n_records > 0


def test_preview_values_are_short_and_readable():
    assert content.preview_value(wb.double(3.5), 'double') == '3.5'
    assert content.preview_value(wb.boolean(True), 'boolean') == 'True'
