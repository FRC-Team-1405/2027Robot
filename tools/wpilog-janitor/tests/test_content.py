BOTH = ('replay', 'logbench')
N = 200                      # cycles in the synthetic logs


def d(v):
    return wb.double(v)


def make_log(series, cycle_us=20_000, t0=1_000_000, offsets=None, typ='double'):
    """series: {name: [values per cycle]}; a value of None means "not logged this cycle". `offsets` shifts an
    entry's timestamps (in µs) so equal data is logged at different instants. Cycles are marked by /Timestamp."""
    b = wb.LogBuilder()
    b.entry('/Timestamp', 'int64', t0)
    for name in series:
        b.entry(name, typ if not isinstance(typ, dict) else typ.get(name, 'double'), t0)
    n = max(len(v) for v in series.values())
    rows = []
    for k in range(n):
        t = t0 + k * cycle_us
        b.data('/Timestamp', t, wb.int64(t))
        for name, vals in series.items():
            if k < len(vals) and vals[k] is not None:
                b.data(name, t + (offsets or {}).get(name, 0), d(vals[k]) if isinstance(vals[k], (int, float)) else vals[k])
    return b.build()


def wave(k, f=0.37):
    return round(((k * f) % 7) - 3, 3)


def stats_of(raw, ranges=None):
    ix = build_index(raw)
    return ix, content.analyze_content(raw, ix.header_end, ranges)


def by_name(stats):
    return {s.name: s for s in stats.values()}


