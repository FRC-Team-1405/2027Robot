# ── dedupe ──────────────────────────────────────────────────────────────────────────────────────

def test_constants_are_never_grouped_as_duplicates():
    raw = make_log({'/Zero/A': [0.0] * N, '/Zero/B': [0.0] * N, '/Zero/C': [0.0] * N, '/Real': [wave(k) for k in range(N)]})
    _, st = stats_of(raw)
    names = {st[i].name for i in dedupe.constants(st)}
    assert {'/Zero/A', '/Zero/B', '/Zero/C'} <= names and '/Real' not in names
    assert dedupe.exact_groups(st, BOTH) == []


def test_identical_and_values_only_groups_with_keeper_and_recoverable_bytes():
    v = [wave(k) for k in range(N)]
    raw = make_log({'/Pickup/Velocity': v, '/RealOutputs/Pickup/Velocity': v, '/Vision/Raw': v[:100] + v[:100],
                    '/Vision/Copy': v[:100] + v[:100], '/Other/Different': [wave(k, 0.11) for k in range(N)]},
                   offsets={'/RealOutputs/Pickup/Velocity': 3_000})
    _, st = stats_of(raw)
    groups = {g.kind: g for g in dedupe.exact_groups(st, BOTH)}
    assert set(groups) == {'identical', 'values'}
    g = groups['values']
    assert st[g.keeper].name == '/Pickup/Velocity'                                   # the replay-input side is kept
    assert [st[i].name for i in g.members if i != g.keeper] == ['/RealOutputs/Pickup/Velocity']
    assert g.recoverable_bytes == st[[i for i in g.members if i != g.keeper][0]].bytes
    assert g.blocked == [] and not g.weak and 'different instants' in g.evidence
    ident = groups['identical']
    assert ident.evidence.startswith('all 200 values match') and 'same instants' in ident.evidence


def test_protected_non_keepers_are_reported_as_blocked():
    v = [wave(k) for k in range(N)]
    raw = make_log({'/Vision/A/Raw': v, '/Vision/A/Copy': v})
    _, st = stats_of(raw)
    (g,) = dedupe.exact_groups(st, BOTH)
    assert len(g.blocked) == 1 and g.blocked[0] != g.keeper                          # both are replay inputs
    (g2,) = dedupe.exact_groups(st, ())
    assert g2.blocked == []                                                          # nothing protected -> nothing blocked


def test_short_series_that_match_are_flagged_weak():
    raw = make_log({'/A/Flag': [0.0] * 50 + [1.0] * 150, '/B/Flag': [0.0] * 50 + [1.0] * 150})
    _, st = stats_of(raw)
    (g,) = dedupe.exact_groups(st, BOTH)
    assert g.weak                                                                    # one flip each: could easily be coincidence


def test_near_duplicates_and_same_name_different_data():
    v = [wave(k) for k in range(N)]
    almost = list(v); almost[100] += 0.5                                              # 1 of 200 differs -> 99.5%, below 99.9%
    raw = make_log({'/Foo/Bar': v, '/RealOutputs/Foo/Bar': almost})
    ix, st = stats_of(raw)
    ex = dedupe.exact_groups(st, BOTH)
    near, twins = dedupe.near_groups_and_twins(raw, ix.header_end, st, ex, BOTH)
    assert ex == [] and near == []                                                   # 99.5% is under the threshold
    (t,) = twins
    assert t.relation == 'different' and '99.5' in t.note and t.key == 'Foo/Bar'

    big = [wave(k) for k in range(3000)]
    nearly = list(big); nearly[1500] += 0.5                                           # 1 of 3000 differs -> 99.97%
    raw = make_log({'/Foo/Bar': big, '/Baz/Qux': nearly})
    ix, st = stats_of(raw)
    near, twins = dedupe.near_groups_and_twins(raw, ix.header_end, st, [], BOTH)
    assert len(near) == 1 and near[0].kind == 'near' and '99.97%' in near[0].evidence and twins == []


def test_twins_with_different_lengths_and_types():
    raw = make_log({'/A/x': [wave(k) for k in range(N)], '/RealOutputs/A/x': [wave(k) for k in range(50)]})
