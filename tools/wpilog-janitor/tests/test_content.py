def test_stopping_early_after_the_last_period_changes_nothing(monkeypatch):
    """With the index's entry list the pass ends when the last period does; the result must equal a full read,
    including entries that are only started after the window."""
    b = wb.LogBuilder()
    b.entry('/Timestamp', 'int64', 1_000_000)
    b.entry('/Early', 'double', 1_000_000)
    for k in range(300):
        t = 1_000_000 + k * 20_000
        b.data('/Timestamp', t, wb.int64(t))
        b.data('/Early', t, d(wave(k)))
        if k == 250:
            b.entry('/Late', 'double', t)                     # started long after the window
        if k >= 250:
            b.data('/Late', t, d(float(k)))
    raw = b.build()
    ix = build_index(raw)
    rng = [(r.lo_us, r.hi_us) for r in resolve_plan(ix, TrimPlan([Segment(1.0, 2.0)])).ranges]

    consumed = []
    real = content.iter_records

    def counting(buf, pos):
        for rec in real(buf, pos):
            consumed.append(1)
            yield rec

    monkeypatch.setattr(content, 'iter_records', counting)
    full = content.analyze_content(raw, ix.header_end, rng)
    n_full = len(consumed)
    consumed.clear()
    fast = content.analyze_content(raw, ix.header_end, rng, ix.entries)
    n_fast = len(consumed)

    strip = lambda st: {i: (s.name, s.type, s.n_records, s.bytes, s.n_changes, s.distinct, s.seq_hash, s.time_hash, s.first_ts_us, s.last_ts_us) for i, s in st.items()}
    assert strip(fast) == strip(full)
    assert by_name(fast)['/Late'].n_records == 0 and by_name(fast)['/Early'].n_records == 50
    assert n_full == 300 + 300 + 50 + 3                          # the full read visits every record
    assert n_fast < n_full / 2                                   # the early stop does not
